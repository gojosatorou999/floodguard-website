// dev check: an Explore button opens the registration form; a save posts the right row; only then the join link shows.
import { chromium } from "playwright";
import { readFileSync } from "node:fs";
const BASE = process.env.QA_BASE || "http://localhost:5173";
const URL_ = JSON.parse(readFileSync("webinar.config.json", "utf8")).url;
const b = await chromium.launch();
const out = []; const ok = (n, c, x = "") => out.push(`${c ? "PASS" : "FAIL"}  ${n}${x ? " — " + x : ""}`);
const ctx = await b.newContext({ viewport: { width: 1280, height: 860 }, colorScheme: "light" });
await ctx.addInitScript(() => { try { sessionStorage.setItem("fg_webinar_invite", "1"); } catch (_) {} });
const p = await ctx.newPage();
const errs = []; p.on("pageerror", e => errs.push(e.message)); p.on("console", m => m.type() === "error" && errs.push(m.text()));
let posted = null;
await p.route("**/sb/rest/v1/webinar_registrations**", async r => { posted = r.request().postDataJSON(); await r.fulfill({ status: 201, contentType: "application/json", body: "" }); });
await p.goto(BASE + "/platform.html", { waitUntil: "load" });
const nav = p.waitForEvent("framenavigated", { timeout: 1500 }).catch(() => null);
await p.locator('a.tExplore[data-webinar]').first().click();
await p.waitForSelector("dialog.wbReg[open]", { timeout: 6000 });
ok("Explore opens the form, not Zoom", true);
ok("page did not navigate away", p.url().startsWith(BASE));
await p.locator(".wrGo").click();
ok("empty submit shows field errors", await p.locator(".wrF.bad").count() > 0);
ok("nothing posted on invalid submit", posted === null);
await p.fill('input[name="name"]', "Asha Rao");
await p.fill('input[name="email"]', "asha@example.in");
await p.fill('input[name="organisation"]', "Example Re");
await p.selectOption('select[name="sector"]', "Insurance & Reinsurance");
await p.fill('textarea[name="interest"]', "Flood pricing for our portfolio");
await p.check('input[name="consent"]');
ok("join link not shown before saving", await p.locator(".wrDone").count() === 0);
await p.locator(".wrGo").click();
await p.waitForSelector(".wrDone", { timeout: 6000 });
ok("row posted to webinar_registrations", !!posted, JSON.stringify(posted));
ok("row has the form fields and consent", posted?.name === "Asha Rao" && posted?.email === "asha@example.in" && posted?.organisation === "Example Re" && posted?.consent === true && posted?.sector === "Insurance & Reinsurance");
ok("no honeypot or unknown columns sent", posted && !("website" in posted));
ok("join link points at the configured URL", (await p.locator(".wrDone a.wbGo").getAttribute("href")) === URL_);
await p.screenshot({ path: "qa-shots/gate-joined.png" });
await p.locator(".wbX").click();
ok("closing the form", await p.locator("dialog.wbReg[open]").count() === 0);
// same device again: straight to the join step, no second form
await p.locator('a.tExplore[data-webinar]').first().click();
await p.waitForSelector("dialog.wbReg[open] .wrDone", { timeout: 4000 });
ok("returning device goes straight to join", true);
ok("errors on page", errs.filter(e => !/favicon|Failed to load resource|\[vite\]/.test(e)).length === 0, errs.join(" | ").slice(0, 200));
await b.close();
console.log(out.join("\n"));
